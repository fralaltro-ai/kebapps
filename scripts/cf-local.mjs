#!/usr/bin/env node
/**
 * Local Cloudflare Workers test environment (OpenNext + `wrangler dev`).
 *
 *   npm run setup:env:local   -> writes .dev.vars (runtime vars of the Worker)
 *   npm run build:cf:local    -> writes .dev.vars, then builds with the local overrides
 *   npm run dev:cf            -> wrangler dev on http://localhost:8787
 */
import fs from "node:fs";
import path from "node:path";
import { spawnSync } from "node:child_process";

const ROOT = path.resolve(path.dirname(new URL(import.meta.url).pathname), "..");
const LOCAL_URL = "http://localhost:8787";

function fail(msg) {
  console.error(`\n❌ ${msg}\n`);
  process.exit(1);
}

function parseEnvFile(content) {
  const out = {};
  for (const rawLine of content.split(/\r?\n/)) {
    const line = rawLine.trim();
    if (!line || line.startsWith("#")) continue;
    const eqIdx = line.indexOf("=");
    if (eqIdx === -1) continue;
    const key = line.slice(0, eqIdx).trim().replace(/^export\s+/, "");
    let val = line.slice(eqIdx + 1).trim();
    if ((val.startsWith('"') && val.endsWith('"')) || (val.startsWith("'") && val.endsWith("'"))) {
      val = val.slice(1, -1);
    }
    if (key) out[key] = val;
  }
  return out;
}

const envPath = path.join(ROOT, ".env.local");
if (!fs.existsSync(envPath)) fail(".env.local non trovato.");
const base = parseEnvFile(fs.readFileSync(envPath, "utf-8"));

const dedicatedTurnstile = Boolean(base.LOCAL_TURNSTILE_SITE_KEY && base.LOCAL_TURNSTILE_SECRET_KEY);
const localSiteKey = base.LOCAL_TURNSTILE_SITE_KEY || base.NEXT_PUBLIC_TURNSTILE_SITE_KEY || "";
const localSecret = base.LOCAL_TURNSTILE_SECRET_KEY || base.TURNSTILE_SECRET_KEY || "";

const vars = { ...base };
delete vars.LOCAL_TURNSTILE_SITE_KEY;
delete vars.LOCAL_TURNSTILE_SECRET_KEY;

Object.assign(vars, {
  NEXT_PUBLIC_DISABLE_PAID_APIS: vars.NEXT_PUBLIC_DISABLE_PAID_APIS ?? "1",
  DISABLE_PAID_APIS: vars.DISABLE_PAID_APIS ?? "1",
  NEXT_PUBLIC_SITE_URL: LOCAL_URL,
  TURNSTILE_SECRET_KEY: localSecret,
  NEXT_PUBLIC_TURNSTILE_SITE_KEY: localSiteKey,
});

const command = process.argv[2] || "vars";

function writeDevVars() {
  const body =
    "# Generated by scripts/cf-local.mjs — local Workers runtime overrides. Do not commit.\n" +
    Object.entries(vars)
      .map(([k, v]) => `${k}=${/[\s#"']/.test(v) ? JSON.stringify(v) : v}`)
      .join("\n") +
    "\n";
  const target = path.join(ROOT, ".dev.vars");
  fs.writeFileSync(target, body, { mode: 0o600 });
  fs.chmodSync(target, 0o600);

  console.log("✅ .dev.vars scritto.");
  console.log(
    "   Google Maps key: " +
      (vars.NEXT_PUBLIC_GOOGLE_MAPS_API_KEY ? "presente" : "ASSENTE") +
      " | Places backend key: " +
      (vars.GOOGLE_PLACES_BACKEND_KEY ? "presente" : "assente") +
      " | NEXT_PUBLIC_DISABLE_PAID_APIS=" +
      vars.NEXT_PUBLIC_DISABLE_PAID_APIS
  );
  console.log(
    "   Turnstile: " +
      (!localSiteKey || !localSecret
        ? "chiavi assenti"
        : dedicatedTurnstile
          ? "widget dedicato (LOCAL_TURNSTILE_*)"
          : "chiavi di .env.local")
  );
}

if (command === "vars") {
  writeDevVars();
} else if (command === "build") {
  if (fs.existsSync(path.join(ROOT, ".env.production.local"))) {
    fail(".env.production.local presente: spostalo fuori dal progetto prima della build locale.");
  }
  writeDevVars();
  console.log("\n▶ npm run build:cf con gli override locali…\n");
  const res = spawnSync("npm", ["run", "build:cf"], {
    cwd: ROOT,
    stdio: "inherit",
    env: {
      ...process.env,
      NEXT_PUBLIC_DISABLE_PAID_APIS: vars.NEXT_PUBLIC_DISABLE_PAID_APIS,
      NEXT_PUBLIC_SITE_URL: LOCAL_URL,
      NEXT_PUBLIC_TURNSTILE_SITE_KEY: localSiteKey,
    },
  });
  if (res.status !== 0) process.exit(res.status ?? 1);
  console.log("✅ Bundle locale OpenNext pronto.");
} else {
  fail(`Comando sconosciuto: ${command}. Usa "vars" o "build".`);
}
